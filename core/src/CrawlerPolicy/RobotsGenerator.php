<?php

declare(strict_types=1);

namespace BsCms\CrawlerPolicy;

final class RobotsGenerator
{
    /**
     * @param array{
     *     preset: string,
     *     bot_rules?: array<string, string>,
     *     disallow_paths?: list<string>,
     *     allow_paths?: list<string>,
     *     sitemap_url?: string
     * } $policy
     * @param list<array<string, mixed>> $botCatalogue
     */
    public function generate(array $policy, array $botCatalogue, string $environment = 'production', int $version = 1): string
    {
        $preset = $policy['preset'] ?? 'balanced';
        $lines = [];
        $lines[] = "# Generated by BS CMS (policy v{$version}). Do not edit by hand; change it in the dashboard.";

        if ($environment === 'staging') {
            $lines[] = "User-agent: *";
            $lines[] = "Disallow: /";
            return implode("\n", $lines) . "\n";
        }

        if ($preset === 'private' && ($policy['block_everything'] ?? false)) {
            $lines[] = "User-agent: *";
            $lines[] = "Disallow: /";
            return implode("\n", $lines) . "\n";
        }

        // Global block
        $lines[] = "User-agent: *";
        $lines[] = "Allow: /";
        $lines[] = "Disallow: /preview/";
        $lines[] = "Disallow: /_preview/";
        $lines[] = "Disallow: /_astro-internal/";

        $customDisallows = (array) ($policy['disallow_paths'] ?? []);
        foreach ($customDisallows as $path) {
            $clean = trim((string) $path);
            if ($clean !== '') {
                $lines[] = "Disallow: {$clean}";
            }
        }

        $botRules = (array) ($policy['bot_rules'] ?? []);

        // Group bots into allowed vs disallowed
        $allowedBots = [];
        $disallowedBots = [];

        foreach ($botCatalogue as $bot) {
            $token = (string) $bot['token'];
            $purpose = (string) ($bot['purpose'] ?? 'other');
            $locked = (bool) ($bot['locked'] ?? false);

            $decision = $botRules[$token] ?? null;

            if ($decision === null) {
                // Preset defaults
                if ($preset === 'open') {
                    $decision = 'allow';
                } elseif ($preset === 'private') {
                    $decision = $locked ? 'allow' : 'disallow';
                } else { // balanced default
                    if ($purpose === 'training') {
                        $decision = 'disallow';
                    } else {
                        $decision = 'allow';
                    }
                }
            }

            if ($locked && $preset !== 'private') {
                $decision = 'allow';
            }

            if ($decision === 'disallow') {
                $disallowedBots[] = $token;
            } elseif ($decision === 'allow' && $purpose !== 'search_engine') {
                // Search engines are covered by User-agent: * Allow: /
                // Explicitly list AI search / user agents so intentions are transparent
                $allowedBots[] = $token;
            }
        }

        if (!empty($allowedBots)) {
            $lines[] = "";
            $lines[] = "# AI search and user-triggered access: allowed";
            foreach ($allowedBots as $token) {
                $lines[] = "User-agent: {$token}";
            }
            $lines[] = "Allow: /";
        }

        if (!empty($disallowedBots)) {
            $lines[] = "";
            $lines[] = "# AI training: not allowed";
            foreach ($disallowedBots as $token) {
                $lines[] = "User-agent: {$token}";
            }
            $lines[] = "Disallow: /";
        }

        $sitemapUrl = (string) ($policy['sitemap_url'] ?? '');
        if ($sitemapUrl !== '') {
            $lines[] = "";
            $lines[] = "Sitemap: {$sitemapUrl}";
        }

        return implode("\n", $lines) . "\n";
    }

    /**
     * @param array{preset?: string, bot_rules?: array<string, string>} $policy
     * @return list<string> Errors
     */
    public function lint(array $policy, string $robotsTxt, string $environment = 'production'): array
    {
        $errors = [];

        if (strlen($robotsTxt) > 500 * 1024) {
            $errors[] = "robots.txt must be under 500 KiB (got " . strlen($robotsTxt) . " bytes).";
        }

        if ($environment === 'production') {
            $preset = $policy['preset'] ?? 'balanced';
            // User-agent: * must not contain Disallow: / in production unless confirmed private
            if ($preset !== 'private') {
                if (preg_match('/User-agent:\s*\*\s*\nDisallow:\s*\/\s*(\n|$)/i', $robotsTxt)) {
                    $errors[] = "User-agent: * must not contain Disallow: / in production.";
                }

                if (preg_match('/User-agent:\s*(Googlebot|Bingbot)\s*\nDisallow:\s*\/\s*(\n|$)/i', $robotsTxt)) {
                    $errors[] = "Search engines (Googlebot / Bingbot) must not be disallowed in production.";
                }
            }
        }

        return $errors;
    }
}
