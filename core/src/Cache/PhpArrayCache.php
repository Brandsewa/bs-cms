<?php

declare(strict_types=1);

namespace BsCms\Cache;

use RuntimeException;

/**
 * PhpArrayCache: compiles plain PHP arrays to disk returning `<?php return [...];`
 * so OPcache keeps compiled configuration, schema metadata, and routes in shared memory.
 */
final class PhpArrayCache
{
    private string $cacheDir;

    public function __construct(string $cacheDir)
    {
        $this->cacheDir = rtrim(str_replace('\\', '/', $cacheDir), '/');
        if (!is_dir($this->cacheDir)) {
            @mkdir($this->cacheDir, 0750, true);
        }
    }

    /**
     * Store array data compiled as an executable PHP array file with atomic write.
     *
     * @param array<string, mixed> $data
     */
    public function set(string $filename, array $data): bool
    {
        $path = $this->resolvePath($filename);
        $exported = var_export($data, true);
        $content = "<?php\n\ndeclare(strict_types=1);\n\n// This file is auto-generated by BS CMS. Do not edit directly.\nreturn {$exported};\n";

        $tempFile = dirname($path) . '/' . bin2hex(random_bytes(8)) . '.tmp';
        if (@file_put_contents($tempFile, $content, LOCK_EX) === false) {
            return false;
        }

        if (!@rename($tempFile, $path)) {
            @unlink($tempFile);
            return false;
        }

        return true;
    }

    /**
     * Load array data from compiled PHP file.
     *
     * @return array<string, mixed>|null
     */
    public function get(string $filename): ?array
    {
        $path = $this->resolvePath($filename);
        if (!is_file($path)) {
            return null;
        }

        /** @var mixed $data */
        $data = require $path;
        return is_array($data) ? $data : null;
    }

    public function has(string $filename): bool
    {
        return is_file($this->resolvePath($filename));
    }

    public function delete(string $filename): bool
    {
        $path = $this->resolvePath($filename);
        if (is_file($path)) {
            return @unlink($path);
        }
        return true;
    }

    private function resolvePath(string $filename): string
    {
        $sanitized = preg_replace('/[^a-zA-Z0-9_\-\.]/', '', $filename);
        if ($sanitized === null || $sanitized === '') {
            throw new RuntimeException("Invalid cache filename: '{$filename}'");
        }

        if (!str_ends_with($sanitized, '.php')) {
            $sanitized .= '.php';
        }

        return "{$this->cacheDir}/{$sanitized}";
    }
}
